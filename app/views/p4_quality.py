def _register(ctx) -> None:
    reg = ctx["agg"]["agg_hypothesis_register"]

    counts = reg["verdict"].value_counts()
    section(
        "Hypothesis register",
        "The dataset notes ship a list of insights students may discover. Each is a plausible "
        "claim and each is testable. Asserting them because they sound like fraud analytics "
        "is the easiest way to publish something false, so every one is tested and reported "
        "whichever way it falls.")

    cols = st.columns(len(counts), gap="small")
    for col, (verdict, n) in zip(cols, counts.items()):
        colour, icon = VERDICT_STYLE.get(verdict, ("#888", "—"))
        with col:
            st.markdown(
                f'<div class="dv-kpi" style="border-left:3px solid {colour}">'
                f'<div class="dv-kpi-label">{icon} {verdict}</div>'
                f'<div class="dv-kpi-value">{n}</div></div>', unsafe_allow_html=True)

    contradicted = reg[reg["verdict"] == "CONTRADICTED"]
    if len(contradicted):
        row = contradicted.iloc[0]
        st.markdown("")
        st.markdown(
            f'<div class="dv-call dv-call-crit" style="border-left-width:5px;padding:1rem 1.1rem">'
            f'<div style="font-size:0.72rem;font-weight:700;letter-spacing:0.06em;'
            f'color:{STATUS["critical"]};margin-bottom:0.35rem">'
            f'✕ CONTRADICTED — THE DATA SHOWS THE OPPOSITE</div>'
            f'<div style="font-size:0.95rem;font-weight:620;color:#0b0b0b;margin-bottom:0.4rem">'
            f'{row["hypothesis"]}</div>'
            f'<div style="font-size:0.83rem;line-height:1.6">{row["reading"]}</div>'
            f'<div style="font-size:0.75rem;color:#898781;margin-top:0.5rem">'
            f'{row["test"]} · {row["statistic"]} · p = {row["p_value"]}</div>'
            f'</div>', unsafe_allow_html=True)

    section("All tested hypotheses")
    order = {"CONTRADICTED": 0, "BORDERLINE": 1, "SUPPORTED": 2,
             "QUANTIFIED": 3, "NOT SUPPORTED": 4, "UNTESTABLE": 5}
    ordered = reg.assign(_o=reg["verdict"].map(order).fillna(9)).sort_values("_o")

    for _, row in ordered.iterrows():
        with st.container(border=True):
            head, chip = st.columns([5, 1])
            with head:
                st.markdown(
                    f'<div style="font-size:0.92rem;font-weight:620;color:#0b0b0b">'
                    f'{row["hypothesis"]}</div>'
                    f'<div style="font-size:0.72rem;color:#898781;margin-top:2px">'
                    f'source: {row["source"]}</div>', unsafe_allow_html=True)
            with chip:
                st.markdown(
                    f'<div style="text-align:right">{verdict_chip(row["verdict"])}</div>',
                    unsafe_allow_html=True)
            st.markdown(
                f'<div style="font-size:0.82rem;color:#52514e;line-height:1.6;'
                f'margin-top:0.4rem">{row["reading"]}</div>', unsafe_allow_html=True)
            st.markdown(
                f'<div style="font-size:0.73rem;color:#898781;margin-top:0.5rem;'
                f'font-family:ui-monospace,SFMono-Regular,Menlo,monospace">'
                f'{row["test"]} · {row["statistic"]}'
                f'{" · p = " + str(row["p_value"]) if pd.notna(row["p_value"]) else ""}</div>',
                unsafe_allow_html=True)

    section("Why this matters")
    notes_rows = reg[reg["source"] == "track1_dataset_notes.txt"]
    rejected = int(notes_rows["verdict"].isin(["NOT SUPPORTED", "CONTRADICTED"]).sum())
    backwards = int((reg["verdict"] == "CONTRADICTED").sum())
    callout(
        "A system that labels everything suspicious is worthless — it generates work "
        f"without information. {rejected} of the {len(notes_rows)} insights suggested by "
        "the dataset notes do not survive testing on this data"
        + (f", and {backwards} runs in the opposite direction to its claim" if backwards else "")
        + ". Reporting that is more useful to a payments risk team than a confident "
        "dashboard built on noise, because it tells them which controls <em>not</em> to build.")
