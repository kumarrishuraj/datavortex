"""Page 4 — Data Quality & Hypothesis Register.

The differentiating page. It shows what the rescue recovered, and then shows
every fraud hypothesis the brief proposed tested against the data — including
the six that do not survive and the one that runs backwards.
"""
from __future__ import annotations

import pandas as pd
import streamlit as st

from app.components import charts
from app.components.theme import SERIES, STATUS, VERDICT_STYLE
from app.components.ui import (
    callout, fmt_inr, fmt_int, fmt_pct, kpi_card, section, verdict_chip,
)


def render(ctx) -> None:
    agg, star = ctx["agg"], ctx["star"]
    st.markdown("# Data Quality & Hypothesis Register")
    st.markdown(
        '<div class="dv-sec-note" style="max-width:58rem">'
        "Two questions a reviewer should be able to answer from this page: what did the "
        "cleaning actually do, and does the system distinguish a real signal from noise. "
        "Every number is read from the generated analytics build."
        "</div>", unsafe_allow_html=True)

    tabs = st.tabs(["Quality scorecard", "Before vs after", "Hypothesis register"])
    with tabs[0]:
        _scorecard(ctx)
    with tabs[1]:
        _before_after(ctx)
    with tabs[2]:
        _register(ctx)


# --------------------------------------------------------------------------
def _scorecard(ctx) -> None:
    agg, star = ctx["agg"], ctx["star"]
    dq = agg["agg_data_quality"]
    tx_all = star["fact_transactions"]
    cb_all = star["fact_chargebacks"]
    users, merchants = star["dim_users"], star["dim_merchants"]

    section("Data quality scorecard",
            "Counts are generated by the pipeline, never hardcoded. Nothing in this table "
            "was deleted — every defect is repaired and flagged, or retained and flagged.")

    rows = [
        ("Duplicate transaction rows collapsed",
         int(-star["recon_rows"].set_index("Metric").loc["Transaction rows", "Difference"]),
         "byte-identical on all 8 columns, verified before collapsing"),
        ("Duplicate complaint rows collapsed",
         int(-star["recon_rows"].set_index("Metric").loc["Chargeback rows", "Difference"]),
         "byte-identical on all 13 fields"),
        ("Amount sign corruption", int(tx_all["amount_sign_invalid"].sum()),
         "repaired to magnitude, flagged; not refunds — no positive twin exists"),
        ("Missing UTR", int(tx_all["utr_missing"].sum()),
         "never fabricated; no UTR collision signal exists once duplicates are removed"),
        ("Malformed chargeback txn_id", int(cb_all["txn_id_malformed"].sum()),
         "5-digit against the 8-digit standard; unrecoverable, retained and flagged"),
        ("Complaints unlinked to a transaction", int(cb_all["txn_unlinked"].sum()),
         "no attributable transaction; excluded from entity metrics, kept in totals"),
        ("Transactions with unresolved merchant", int(tx_all["merchant_unresolved"].sum()),
         "routed to the UNKNOWN dimension member, retained in every total"),
        ("Transactions with unresolved customer", int(tx_all["user_unresolved"].sum()),
         "routed to the UNKNOWN dimension member, retained in every total"),
        ("Customer ID collisions", int(users["identity_ambiguous"].sum()),
         "different people share one ID; all candidates preserved in the bridge table"),
        ("Merchant ID collisions", int(merchants["identity_ambiguous"].sum()),
         "different businesses share one ID; all candidates preserved"),
        ("PAN repaired by homoglyph substitution",
         int((users["pan_status"] == "REPAIRED").sum()),
         "0↔O, 1↔I, 2↔Z, 5↔S, 8↔B applied positionally, kept only when the result is a valid PAN"),
        ("PAN unrepairable (truncated)", int((users["pan_status"] == "TRUNCATED").sum()),
         "9 characters, missing the check letter; fabricating it would invent an identity"),
        ("Reporting delay negative", int(cb_all["delay_negative"].sum()),
         "dispute predates its own transaction timestamp; flagged, not clipped"),
        ("Reporting delay unknown", int(cb_all["delay_missing"].sum()),
         "a timestamp was unparseable; excluded from the delay metric only"),
    ]
    frame = pd.DataFrame(rows, columns=["Defect", "Records", "Treatment"])
    st.dataframe(frame, hide_index=True, width="stretch", height=530,
                 column_config={"Records": st.column_config.NumberColumn(format="localized")})

    section("Attribution coverage", "How much of the book each analysis can actually reach.")
    c = st.columns(4, gap="small")
    cov = [
        ("Chargeback → transaction", 100 * int((~cb_all["txn_unlinked"]).sum()) / len(cb_all),
         "via txn_id, the only trustworthy foreign key"),
        ("Transaction → merchant", 100 * int((~tx_all["merchant_unresolved"]).sum()) / len(tx_all),
         "merchant master coverage"),
        ("Transaction → KYC", 100 * int((~tx_all["user_unresolved"]).sum()) / len(tx_all),
         "KYC record coverage"),
        ("Timestamp with clock time", 100 * int(tx_all["timestamp_time_known"].sum()) / len(tx_all),
         "the rest are date-only and excluded from hourly analysis"),
    ]
    for col, (label, pct, basis) in zip(c, cov):
        with col:
            kpi_card(label, fmt_pct(pct), "", pct, basis)


