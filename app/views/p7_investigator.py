def _examples() -> dict[str, list[str]]:
    return {
        "Dataset notes — the 12 example agent queries":
            [c.question for c in eval_cases.CASES if c.source == eval_cases.NOTES_AGENT],
        "Competition PDF": [c.question for c in eval_cases.CASES if c.source == eval_cases.PDF],
        "More to try": MORE_EXAMPLES,
    }


def _ask(ctx) -> None:
    agg, star = ctx["agg"], ctx["star"]

    # The text box owns its state. A button click writes to that state before the box is
    # drawn in the same run, which is the only way a click can replace an existing question.
    if "investigator_input" not in st.session_state:
        st.session_state["investigator_input"] = DEFAULT_QUESTION

    section("Example questions", "Click one, or type your own below.")
    for g, (group, questions) in enumerate(_examples().items()):
        with st.expander(group, expanded=g == 0):
            cols = st.columns(2, gap="small")
            for i, question in enumerate(questions):
                with cols[i % 2]:
                    if st.button(question, key=f"ex_{g}_{i}", width="stretch"):
                        st.session_state["investigator_input"] = question

    question = st.text_input(
        "Your question", key="investigator_input",
        placeholder="e.g. which merchant category had the highest chargeback rate this quarter?")
    if not question.strip():
        return

    try:
        intent = plan(question)
    except IntentRejected as exc:
        callout(f"<strong>Cannot answer that.</strong> {exc}", kind="warn")
        nearest = suggest_metrics(question)
        if nearest:
            st.markdown("**Closest registered metrics:**")
            for name in nearest:
                metric = semantic.get(name)
                st.markdown(f"- `{name}` — {metric.label}: {metric.definition}")
        return

    try:
        with st.spinner("Resolving intent and computing…"):
            answer = execute(intent, agg, star)
    except Exception as exc:  # noqa: BLE001 — surfaced to the user, never silent
        callout(f"<strong>Execution failed.</strong> {type(exc).__name__}: {exc}", kind="crit")
        return

    st.markdown("---")
    st.markdown(
        f'<div style="font-size:1.24rem;font-weight:660;color:#0b0b0b;letter-spacing:-0.01em">'
        f'{answer.headline}</div>', unsafe_allow_html=True)
    if answer.detail:
        st.markdown(
            f'<div style="font-size:0.88rem;color:#52514e;line-height:1.6;margin-top:0.4rem">'
            f'{answer.detail}</div>', unsafe_allow_html=True)

    _render_chart(answer)

    if answer.caveat:
        callout(answer.caveat, kind=answer.caveat_kind)

    if answer.chart_kind != "table" and answer.table is not None and not answer.table.empty:
        with st.expander(f"Underlying data ({len(answer.table):,} rows)"):
            st.dataframe(answer.table, hide_index=True, width="stretch")

    with st.expander("How this answer was generated"):
        st.markdown("**Resolved intent** — validated against the semantic registry:")
        st.json(intent.as_dict())
        st.markdown("**Provenance**")
        st.dataframe(pd.DataFrame([(k, str(v)) for k, v in answer.provenance.items()],
                                  columns=["Field", "Value"]),
                     hide_index=True, width="stretch")
        st.caption("The intent above is the only thing a language model would produce. Every "
                   "figure in the answer was computed after the intent passed validation.")


def _render_chart(answer) -> None:
    config = {"displayModeBar": False}
    kind = answer.chart_kind
    if kind == "line" and answer.chart_x and answer.chart_series:
        if answer.chart_band:
            actual = [v for v in answer.chart_series.get("Actual", []) if v is not None]
            forecast = [v for v in answer.chart_series.get("Forecast", []) if v is not None]
            fig = charts.forecast_chart(answer.chart_x[:len(actual)], actual,
                                        answer.chart_band["x"], forecast,
                                        answer.chart_band["lower"], answer.chart_band["upper"],
                                        title=answer.chart_title)
        elif len(answer.chart_series) == 1:
            name, values = next(iter(answer.chart_series.items()))
            fig = charts.line(answer.chart_x, values, title=answer.chart_title or name)
        else:
            fig = charts.multi_line(answer.chart_x, answer.chart_series, title=answer.chart_title)
        st.plotly_chart(fig, width="stretch", config=config)
    elif kind in ("bar", "horizontal_bar") and answer.chart_labels:
        if answer.show_ci:
            fig = charts.hbar_with_ci(answer.chart_labels, answer.chart_values, answer.chart_lo,
                                      answer.chart_hi, title=answer.chart_title, xtitle="rate (%)")
        elif kind == "bar":
            fig = charts.vbar(answer.chart_labels, answer.chart_values, title=answer.chart_title)
        else:
            fig = charts.hbar(answer.chart_labels, answer.chart_values, title=answer.chart_title)
        st.plotly_chart(fig, width="stretch", config=config)
    elif kind == "histogram" and answer.chart_values:
        st.plotly_chart(charts.histogram(answer.chart_values, title=answer.chart_title),
                        width="stretch", config=config)
    elif kind == "table" and answer.table is not None and not answer.table.empty:
        st.dataframe(answer.table, hide_index=True, width="stretch",
                     height=min(440, 40 + 35 * len(answer.table)))
    elif kind == "kpi_card" and answer.kpi_value:
        kpi_card("Answer", answer.kpi_value)


