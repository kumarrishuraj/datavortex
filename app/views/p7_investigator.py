def render(ctx) -> None:
    st.markdown("# AI Investigator")
    st.markdown(
        '<div class="dv-sec-note" style="max-width:58rem">'
        "Ask a question about this dataset. It is turned into a typed intent, checked against "
        "the semantic registry, computed by the query engine from the analytics layer, drawn "
        "with a chart chosen by explicit rules, and explained with the caveats the data "
        "requires. No number you see is generated by a language model."
        "</div>", unsafe_allow_html=True)

    tabs = st.tabs(["Ask", "Test matrix", "How it works", "Registry"])
    with tabs[0]:
        _ask(ctx)
    with tabs[1]:
        _matrix()
    with tabs[2]:
        _architecture()
    with tabs[3]:
        _registry()


