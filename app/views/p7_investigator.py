def _matrix() -> None:
    frame = load_agent_eval()
    section("Evaluation matrix",
            "Every example question from the dataset notes and the competition PDF, the team's "
            "demo questions, natural phrasings and safety probes — each planned and executed, "
            "with what a correct answer requires and what the agent produced.")
    if frame is None or frame.empty:
        callout("Run <code>python scripts/run_agent_eval.py</code> to generate the matrix.",
                kind="warn")
        return
    passed = int(frame["passed"].sum())
    charts_used = sorted(c for c in frame["chart"].dropna().unique() if c not in ("—", "none", ""))
    c = st.columns(4, gap="small")
    with c[0]:
        kpi_card("Cases", fmt_int(len(frame)))
    with c[1]:
        kpi_card("Passed", fmt_int(passed))
    with c[2]:
        kpi_card("Failed", fmt_int(len(frame) - passed))
    with c[3]:
        kpi_card("Chart Types Produced", fmt_int(len(charts_used)), ", ".join(charts_used))

    summary = (frame.groupby("source", sort=False)
                    .agg(Questions=("question", "size"), Passed=("passed", "sum"))
                    .reset_index().rename(columns={"source": "Source"}))
    st.dataframe(summary, hide_index=True, width="stretch")

    sources = ["All"] + summary["Source"].tolist()
    chosen = st.selectbox("Source", sources, key="matrix_source")
    view = frame if chosen == "All" else frame[frame["source"] == chosen]
    st.dataframe(
        view[["question", "source", "expected", "actual", "chart", "passed", "failure"]].rename(
            columns={"question": "Question", "source": "Source", "expected": "Expected",
                     "actual": "Actual", "chart": "Chart", "passed": "Pass",
                     "failure": "Why it failed"}),
        hide_index=True, width="stretch", height=480,
        column_config={"Pass": st.column_config.CheckboxColumn()})
    st.caption("Read from the evaluation script's output rather than recomputed on page load. "
               "Re-run the script after changing the agent.")


def _architecture() -> None:
    section("Pipeline", "Each stage passes a typed object forward or refuses.")
    st.code(
        "question\n"
        "   ↓  planner: measure · dimension · time grain · window · series · ranking\n"
        "      (each slot resolved against the semantic registry's own synonyms)\n"
        "structured Intent\n"
        "   ↓  validate_intent()  — registry whitelist + metric/dimension compatibility\n"
        "   ↓  query engine       — registered computation spec, executed in pandas\n"
        "result + denominator + coverage + reconciliation check\n"
        "   ↓  significance test, rate floor and shrinkage where the answer ranks rates\n"
        "   ↓  chart selector     — explicit rules on the result's shape\n"
        "answer + chart + caveats + provenance",
        language="text")

    section("How the chart is chosen")
    st.dataframe(pd.DataFrame([
        ("Detailed records", "Table"),
        ("Anything grouped by day, week, month or quarter", "Line"),
        ("Distribution of a continuous measure", "Histogram"),
        ("Ranking of individual merchants or customers, or many categories", "Horizontal bar"),
        ("Comparison of a small set of categories", "Bar"),
        ("A single figure", "KPI card"),
    ], columns=["Shape of the answer", "Chart"]), hide_index=True, width="stretch")
    st.caption("Time always wins: a measure broken down over time is a trend and is drawn as a "
               "line. Two measures on different scales are never put on one chart.")

    section("What the model is not allowed to do")
    left, right = st.columns(2, gap="medium")
    with left:
        st.markdown(
            "- perform arithmetic — every number is computed by the query engine\n"
            "- invent a metric — only registry entries resolve\n"
            "- generate SQL — there is no SQL surface to generate into\n"
            "- choose a chart outside the allowed list\n"
            "- label anyone fraudulent — the data has no fraud label\n"
            "- expose PAN, Aadhaar or account numbers — only masked forms exist\n"
            "- answer outside the dataset — unplannable questions are refused")
    with right:
        st.markdown("**Guarded tokens**")
        st.code("  ".join(FORBIDDEN_TOKENS), language="text")

    section("Try the guards")
    for probe in PROBES:
        with st.container(border=True):
            st.markdown(f"`{probe}`")
            try:
                plan(probe)
                st.markdown("— accepted (unexpected)")
            except IntentRejected as exc:
                st.markdown(f'<div style="font-size:0.82rem;color:{STATUS["critical"]}">'
                            f'Refused — {exc}</div>', unsafe_allow_html=True)


def _registry() -> None:
    section("Metric registry",
            "Every metric the investigator can reach, with the computation spec the query engine "
            "executes. A metric that is not here cannot be answered, by design.")
    reg = semantic.registry_frame()
    st.dataframe(
        reg[["metric", "label", "unit", "definition", "formula", "source", "aggregation",
             "trendable", "coverage_basis"]],
        hide_index=True, width="stretch", height=460,
        column_config={"definition": st.column_config.TextColumn(width="large")})
    section("Dimension registry")
    st.dataframe(semantic.dimension_frame(), hide_index=True, width="stretch")
    c = st.columns(3, gap="small")
    with c[0]:
        kpi_card("Registered Metrics", fmt_int(len(semantic.METRICS)))
    with c[1]:
        kpi_card("Registered Dimensions", fmt_int(len(semantic.DIMENSIONS)))
    with c[2]:
        kpi_card("Allowed Chart Types", fmt_int(len(semantic.ALLOWED_CHARTS)))
