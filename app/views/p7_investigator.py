"""Page 7 — AI Investigator.

The language model is not in the number. A question becomes a typed intent, the
intent is validated against the semantic registry, the semantic query engine
computes the answer from materialized Parquet, a rule-based selector picks the
chart, and the narrative is assembled around figures computed first.

The planner shipped here is deterministic and needs no API key, so a live demo
cannot fail on a network call. A language model, when added, produces the same
Intent object and passes through the same validation.
"""
