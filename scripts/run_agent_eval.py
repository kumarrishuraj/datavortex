"""Run the AI Investigator evaluation matrix and write docs/agent_test_matrix.md.

    python scripts/run_agent_eval.py

Every case is planned and executed against the built analytics layer. The report
records, per question, what a correct answer must look like, what the agent
actually produced, the chart it chose, and pass or fail with the reason. The
process exits non-zero if any case fails, so it can gate a build.
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from scripts.build_report import md_table  # noqa: E402
from src.agent.eval_cases import CASES, evaluate  # noqa: E402
from src.config import DOCS_DIR, PROCESSED_DIR  # noqa: E402


def load() -> tuple[dict, dict]:
    agg = {p.stem: pd.read_parquet(p) for p in (PROCESSED_DIR / "analytics").glob("*.parquet")}
    star = {p.stem: pd.read_parquet(p) for p in PROCESSED_DIR.glob("*.parquet")}
    return agg, star


def main() -> int:
    t0 = time.time()
    agg, star = load()
    rows = [evaluate(case, agg, star) for case in CASES]
    frame = pd.DataFrame(rows)

    summary = (frame.groupby("source", sort=False)
                    .agg(questions=("question", "size"), passed=("passed", "sum"))
                    .reset_index())
    summary["failed"] = summary["questions"] - summary["passed"]
    total, passed = len(frame), int(frame["passed"].sum())
    charts = sorted(c for c in frame["chart"].dropna().unique() if c not in ("—", "none", ""))

    out: list[str] = []
    w = out.append
    w("# DataVortex — AI Investigator Test Matrix")
    w("_Generated by `scripts/run_agent_eval.py`. Every question below was planned and executed "
      "against the built analytics layer; nothing in this table is written by hand._\n")
    w(f"**{passed} of {total} cases pass.** Chart types produced: {', '.join(charts)}.\n")
    w("Sources: every *Example agent query* and *Example dashboard question* in "
      "`track1_dataset_notes.txt`; the example questions in the competition PDF; the team's demo "
      "questions; natural phrasings of the same intents; and safety probes that must be refused.\n")
    w("A case passes only if the intent kind, registered metric, dimension, time grain, chart "
      "type, no-result behaviour and required caveat all match what a correct answer needs. "
      "Line charts additionally must carry real series data.\n")
    w("## Summary by source\n")
    w(md_table(summary.rename(columns={"source": "Source", "questions": "Questions",
                                       "passed": "Passed", "failed": "Failed"})))
    w("")
    for source in summary["source"]:
        sub = frame[frame["source"] == source]
        w(f"## {source}\n")
        table = pd.DataFrame({
            "Question": sub["question"],
            "Expected": sub["expected"],
            "Actual": sub["actual"],
            "Chart": sub["chart"],
            "Pass/Fail": ["PASS" if p else "FAIL" for p in sub["passed"]],
        })
        if not sub["passed"].all():
            table["Why it failed"] = sub["failure"].fillna("")
        w(md_table(table))
        w("")

    frame.to_parquet(PROCESSED_DIR / "analytics" / "agent_eval.parquet", index=False)

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    path = DOCS_DIR / "agent_test_matrix.md"
    path.write_text("\n".join(out), encoding="utf-8")

    print(summary.to_string(index=False))
    print(f"\n{passed}/{total} passed in {time.time() - t0:.1f}s -> {path}")
    for row in rows:
        if not row["passed"]:
            print(f"  FAIL  {row['question']}  —  {row['failure']}")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
